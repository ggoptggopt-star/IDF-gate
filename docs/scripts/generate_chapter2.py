def add_equation(doc: Document, latex_str: str, eq_label: str) -> None:
    """แทรกสมการ Word Equation (OMML) กึ่งกลางพร้อมตั้งค่าขนาด 16 pt และระบุเลขสมการ"""
    omath_para = latex_to_omml(latex_str)

    # กำหนดการจัดกึ่งกลางใน OMML
    omath_para_pr = etree.Element(f"{{{OMML}}}oMathParaPr")
    jc = etree.SubElement(omath_para_pr, f"{{{OMML}}}jc")
    jc.set(f"{{{OMML}}}val", "center")
    omath_para.insert(0, omath_para_pr)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.keep_with_next = True

    # ตั้งขนาดฟอนต์เริ่มต้นของย่อหน้าสมการเป็น Cambria Math 14 pt (สมดุลกับ TH SarabunPSK 16 pt)
    pPr = p._element.get_or_add_pPr()
    p_rpr = parse_xml(
        f'<w:rPr {nsdecls("w")}>'
        '  <w:rFonts w:ascii="Cambria Math" w:hAnsi="Cambria Math" w:cs="Cambria Math"/>'
        '  <w:sz w:val="28"/><w:szCs w:val="28"/>'
        "</w:rPr>"
    )
    pPr.append(p_rpr)
    p._element.append(omath_para)

    # ระบุเลขกำกับสมการชิดขวาใต้สมการอย่างเป็นระเบียบ
    add_styled_paragraph(
        doc,
        f"({eq_label})",
        size_pt=16,
        bold=False,
        alignment=WD_ALIGN_PARAGRAPH.RIGHT,
        space_before_pt=0.0,
        space_after_pt=4.0,
    )


def add_styled_table(
    doc: Document,
    caption: str,
    headers: list[str],
    rows_data: list[list[str]],
    col_widths_cm: list[float],
    col_alignments: list,
) -> None:
    """สร้างตารางมาตรฐานความกว้างคงที่ 14.65 ซม. พร้อมหัวตารางสีอ่อนและป้องกันการตัดแถวข้ามหน้า"""
    add_styled_paragraph(
        doc,
        caption,
        size_pt=16,
        bold=True,
        alignment=WD_ALIGN_PARAGRAPH.LEFT,
        space_before_pt=6.0,
        space_after_pt=4.0,
        keep_with_next=True,
    )

    table = doc.add_table(rows=1 + len(rows_data), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    set_fixed_table_widths(table, col_widths_cm)

    # แถวหัวตาราง
    header_row = table.rows[0]
    prevent_row_split(header_row)
    set_repeat_table_header(header_row)
    for c_idx, title in enumerate(headers):
        cell = header_row.cells[c_idx]
        set_cell_borders(cell, top=True, bottom=True, left=True, right=True, sz="4")
        set_cell_shading(cell, "E8EEF7")
        set_cell_margins(cell, top=70, bottom=70, left=100, right=100)
        set_cell_text(cell, title, size_pt=16, bold=True, alignment=WD_ALIGN_PARAGRAPH.CENTER)

    # แถวข้อมูล
    for r_idx, row_vals in enumerate(rows_data):
        row = table.rows[1 + r_idx]
        prevent_row_split(row)
        for c_idx, val in enumerate(row_vals):
            cell = row.cells[c_idx]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP
            set_cell_borders(cell, top=True, bottom=True, left=True, right=True, sz="4")
            set_cell_margins(cell, top=60, bottom=60, left=100, right=100)
            p = set_cell_text(cell, val, size_pt=16, bold=False, alignment=col_alignments[c_idx])
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER if col_alignments[c_idx] == WD_ALIGN_PARAGRAPH.CENTER else WD_ALIGN_VERTICAL.TOP
            p.paragraph_format.line_spacing = 1.0

    add_styled_paragraph(doc, "", size_pt=16, space_after_pt=4.0)


