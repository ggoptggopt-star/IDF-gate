// Helper: Calculate distance in KM
export function calcDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

// Instant Exact Match Filter for any query across Ongkharak
export function searchVerifiedLocations(query: string, subdistrictFilter?: string): VerifiedLocation[] {
  const q = query.trim().toLowerCase();

  let pool = VERIFIED_LOCATIONS;
  if (subdistrictFilter && subdistrictFilter !== 'all') {
    pool = pool.filter((loc) => loc.subdistrict === subdistrictFilter);
  }

  if (!q) return pool.slice(0, 15);

  return pool
    .filter((loc) => {
      // 1. Direct name match
      if (loc.name.toLowerCase().includes(q)) return true;
      // 2. Subdistrict match
      if (loc.subdistrict.toLowerCase().includes(q)) return true;
      // 3. Keyword match
      if (loc.keywords.some((k) => k.toLowerCase().includes(q) || q.includes(k.toLowerCase()))) return true;
      // 4. Address match
      if (loc.address.toLowerCase().includes(q)) return true;
      return false;
    })
    .sort((a, b) => {
      const aStarts = a.name.toLowerCase().startsWith(q) ? 1 : 0;
      const bStarts = b.name.toLowerCase().startsWith(q) ? 1 : 0;
      return bStarts - aStarts;
    });
}
